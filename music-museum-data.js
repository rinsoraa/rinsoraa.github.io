/* ============================================================
   music-museum-data.js —— 「音乐博物馆」的**摆位覆写**表
   ------------------------------------------------------------
   分工（别搞混，这是这个文件存在的全部理由）：

     music-data.js          →  「歌曲**是什么**」（title / artist / cover / src / lrc）
     music-museum-data.js   →  「歌曲在博物馆里**想摆在哪**」（可选，见下）

   所以这里一个字的歌曲信息都不复制。
   标题、歌手、封面、音频地址、歌词全部在运行时从 window.RINSORA_MUSIC 取。

   ⚠️⚠️ 最重要的约定：**唱片墙以曲库为准，这个文件只做「覆写」**
   ------------------------------------------------------------
   博物馆里「一首歌 = 一张唱片」，这是引擎自己按 music-data.js 的
   tracks[] 生成的。这个文件**不再是**「要展示哪些唱片」的清单，
   它只回答一个问题：「我已经有偏好的那几首，想摆在哪？」

   为什么改成这样（都是踩出来的）：
     · 原来这里是一份手写的 records[] 清单，引擎只认清单 ——
       写重了，同一首歌就在墙上出现两张（看起来就像 bug）；
       而新加的歌没手动补一条，就**永远上不了墙**。
     · 现在：没写进 spots 的歌由引擎**自动摆位**（见 music-museum.js
       的 autoSpot），加歌 / 删歌 / 换封面，墙自己跟着变。

   字段说明
     spots         : 摆位覆写表，键 = music-data.js 里 tracks[].id
        x / y       唱片中心位置，单位 %（相对展厅可视区）。
                    x: 0 = 左边缘，100 = 右边缘；y: 0 = 顶，100 = 底。
        scale       缩放，1 = 基准尺寸（--mm-size，见 music-museum.css）
        rotation    静止姿态的角度（deg）
        depth       0~1，越大越远：越远越淡、越模糊、视差位移越小。
                    ⚠️ 自动摆位的约定是「越靠下 = 越远」，跟这套观感对齐。
        label?      可选，覆写唱片上那行小字；不写就用 artist
        note?       可选，**这一处陈列**的附注（详情里显示成 NOTE 一行）
       —— 以上字段**全都可以只写一部分**，缺的由自动摆位补。
       同一首歌写多条？不会重复上墙，只有第一条生效（引擎按 id 去重）。

     records[]    : 老写法（手写清单），仍然认，但语义已变成「覆写」：
                    只取每个 musicId 的第一条，且不再决定「展示哪些」。
                    新写的东西请用 spots。

   换个说法：想给某首歌指定位置 → 写进 spots；
             想让所有歌都自己排 → 把 spots 清空，一样能看。
   ============================================================ */
