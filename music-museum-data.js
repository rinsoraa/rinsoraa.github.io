/* ============================================================
   music-museum-data.js —— 「音乐博物馆」的**覆写**表
   ------------------------------------------------------------
   分工（别搞混，这是这个文件存在的全部理由）：

     music-data.js          →  「歌曲**是什么**」（title / artist / cover / src / lrc）
     music-museum-data.js   →  「这首歌在博物馆里想**额外标注**什么」（可选）

   所以这里一个字的歌曲信息都不复制。
   标题、歌手、封面、音频地址、歌词全部在运行时从 window.RINSORA_MUSIC 取。

   ⚠️⚠️ 最重要的约定：**馆藏以曲库为准，这个文件只做「覆写」**
   ------------------------------------------------------------
   博物馆里「一首歌 = 一张唱片」，这是引擎自己按 music-data.js 的
   tracks[] 生成的。这个文件**不是**「要展示哪些唱片」的清单。

   为什么改成这样（都是踩出来的）：
     · 原来这里是一份手写的 records[] 清单，引擎只认清单 ——
       写重了，同一首歌就在墙上出现两张（看起来就像 bug）；
       而新加的歌没手动补一条，就**永远上不了墙**。
     · 现在：这个文件整份删掉，馆藏也照样完整。

   ⚠️⚠️ 第六轮：**摆位字段（x / y / scale / rotation / depth）已全部作废**
   ------------------------------------------------------------
   为什么作废：第六轮把「馆藏怎么摆」从「手写坐标 + 自由阵列」换成了
   **左侧无限循环扇形** —— 位置是 `offset × 角度` 沿椭圆弧解算出来的
   （见 music-museum.js 的 fanGeometry / fanLayout），缩放 / 透明度 /
   模糊由 |offset| 在同一条曲线上插值。也就是说：

       一张唱片的「位置 / 大小 / 清晰度」全部是**焦点相对它的距离**的函数，
       不是它自己的属性。

   所以 x / y / scale / rotation / depth 这五个字段现在**没有任何读取方**，
   留在文件里就是「写了没人读的变量」（项目铁律：那是债）。
   想让某首歌更醒目 → 它自动就是：滚到它，它就是焦点。

   字段说明（只剩两个，都可选）
     spots         : 覆写表，键 = music-data.js 里 tracks[].id
        label?      可选，覆写档案面板里的「歌手」那一行；不写就用 artist
        note?       可选，**这一处陈列**的附注（档案面板里显示成 NOTE 一行）
       —— 两个字段都可以只写一个，也可以两个都不写。
       同一首歌写多条？不会重复上墙，只有第一条生效（引擎按 id 去重）。

     records[]    : 老写法（手写清单），仍然认，但语义已变成「覆写」：
                    只取每个 musicId 的第一条，且不再决定「展示哪些」、
                    也不再参与摆位。新写的东西请用 spots。

   换个说法：想让某首歌多一行注释 → 写进 spots；
             什么都不写 → 馆藏一样完整、能滚、能动、能放。
   ============================================================ */
window.RINSORA_MUSIC_MUSEUM = {
  "version": 3,
  "spots": {
    /* 第六轮之后这里只剩 label / note 两种字段可用，用法示例：

         "m-muashb2d": { "note": "进门第一首", "label": "空凛" },

       把示例那一行**复制到本注释外面**（注意给它补上前后逗号）即可生效。
       目前**没有**需要覆写的条目 —— 所以这里是空的，这不是漏写。 */
  }
};
